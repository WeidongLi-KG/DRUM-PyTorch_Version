#!/usr/bin/env python3
# eval/evaluate.py
import numpy as np
import os
import sys
import pickle
import argparse
import time
from collections import defaultdict

def evaluate():
    parser = argparse.ArgumentParser()
    parser.add_argument('--preds', default="", type=str, required=True,
                        help="Predictions file (CSV lines: q,h,t,pred1,pred2,...,pred_true_head)")
    parser.add_argument('--truths', default=None, type=str,
                        help="Truths pickle generated by get_truths.py (folder/truths.pckl).")
    parser.add_argument('--top_k', default=10, type=int)
    parser.add_argument('--raw', default=False, action="store_true")
    parser.add_argument('--v', default=False, action="store_true")
    option = parser.parse_args()
    print(option)
    start = time.time()

    if not option.raw:
        if option.truths is None:
            raise ValueError("truths file must be provided unless --raw is set.")
        with open(option.truths, "rb") as f:
            truths = pickle.load(f)
        query_heads = truths.get("query_head", {})
        query_tails = truths.get("query_tail", {})
    else:
        query_heads = {}
        query_tails = {}

    hits = 0.0
    hits_by_q = defaultdict(list)
    ranks = 0.0
    ranks_by_q = defaultdict(list)
    rranks = 0.0
    line_cnt = 0

    with open(option.preds, "r", encoding="utf-8") as f:
        lines = [l.strip().split(",") for l in f if l.strip()]
    line_cnt = len(lines)

    for l in lines:
        assert(len(l) > 3)
        q, h, t = l[0:3]
        this_preds = l[3:]
        assert(h == this_preds[-1])
        hitted = 0.0

        if not option.raw:
            if q.startswith("inv_"):
                q_ = q[len("inv_"):]
                also_correct = query_heads.get((q_, t), [])
            else:
                also_correct = query_tails.get((q, t), [])
            also_correct = set(also_correct)
            assert(h in also_correct)
            filtered = set(this_preds[:-1]) - also_correct
            filtered.add(this_preds[-1])
            this_preds_filtered_len = len(filtered)
            if this_preds_filtered_len <= option.top_k:
                hitted = 1.0
            rank = this_preds_filtered_len
        else:
            if len(this_preds) <= option.top_k:
                hitted = 1.0
            rank = len(this_preds)

        hits += hitted
        ranks += rank
        rranks += 1.0 / rank
        hits_by_q[q].append(hitted)
        ranks_by_q[q].append(rank)

    print("Hits at %d is %0.4f" % (option.top_k, hits / max(1, line_cnt)))
    print("Mean rank %0.2f" % (1.0 * ranks / max(1, line_cnt)))
    print("Mean Reciprocal Rank %0.4f" % (1.0 * rranks / max(1, line_cnt)))

    if option.v:
        hits_by_q_mean = sorted([[k, np.mean(v), len(v)] for k, v in hits_by_q.items()], key=lambda xs: xs[1], reverse=True)
        for xs in hits_by_q_mean:
            xs += [np.mean(ranks_by_q[xs[0]]), np.std(ranks_by_q[xs[0]])]
            print(", ".join([str(x) for x in xs]))

    print("Time %0.3f mins" % ((time.time() - start) / 60.0))
    print("="*36 + "Finish" + "="*36)

if __name__ == "__main__":
    evaluate()
